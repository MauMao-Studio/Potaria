"""
Potaria - Generated Projectile Assets Verification Suite
Tests the 40 library projectile assets (P01 to P40) generated by AssetFactory:
1. File existence on disk in assets/projectiles/
2. Resolution: Exactly 32x32 pixels with transparent background
3. Opaque pixel count within valid sprite bounds (no empty or solid sprites)
4. Bitwise uniqueness: 40 unique SHA-256 digests with zero collisions
5. AssetFactory projectile dictionary and alias resolution (canonical, snake_case, ID, id_lower)
Developer: Kurados | Pure Python & pygame-ce
"""

import os
import sys
import hashlib
import unittest
from PIL import Image

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))
os.environ["SDL_VIDEODRIVER"] = "dummy"

import pygame
pygame.init()

from src.assets.asset_factory import AssetFactory
from src.assets.projectile_factory import PROJECTILE_BUILDERS


class TestGeneratedProjectileAssets(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.af = AssetFactory()
        cls.proj_dir = os.path.join("assets", "projectiles")
        cls.builder_keys = sorted(PROJECTILE_BUILDERS.keys())

    def test_01_builder_count(self):
        self.assertEqual(len(self.builder_keys), 40, "Expected 40 projectile builders")
        for i in range(1, 41):
            expected_prefix = f"p{i:02d}_"
            matched = [k for k in self.builder_keys if k.startswith(expected_prefix)]
            self.assertEqual(len(matched), 1, f"Missing builder for prefix {expected_prefix}")

    def test_02_disk_files_exist_and_dimensions(self):
        self.assertTrue(os.path.exists(self.proj_dir), "assets/projectiles directory must exist")
        for key in self.builder_keys:
            fname = f"{key}.png"
            fpath = os.path.join(self.proj_dir, fname)
            self.assertTrue(os.path.exists(fpath), f"Projectile file missing: {fname}")

            with Image.open(fpath) as im:
                self.assertEqual(im.size, (32, 32), f"{fname} must be exactly 32x32")
                self.assertEqual(im.mode, "RGBA", f"{fname} must be in RGBA format")
                # Corners must be transparent
                for corner in [(0, 0), (31, 0), (0, 31), (31, 31)]:
                    self.assertEqual(im.getpixel(corner)[3], 0, f"{fname} corner {corner} must be transparent")

    def test_03_opaque_pixel_bounds(self):
        for key in self.builder_keys:
            fname = f"{key}.png"
            fpath = os.path.join(self.proj_dir, fname)
            with Image.open(fpath) as im:
                alpha = im.getchannel("A").tobytes()
                opaque_count = sum(1 for a in alpha if a > 0)
                self.assertGreaterEqual(opaque_count, 30, f"{fname} has too few opaque pixels: {opaque_count}")
                self.assertLessEqual(opaque_count, 700, f"{fname} has too many opaque pixels: {opaque_count}")

    def test_04_bitwise_uniqueness(self):
        digests = {}
        for key in self.builder_keys:
            fpath = os.path.join(self.proj_dir, f"{key}.png")
            with open(fpath, "rb") as f:
                d = hashlib.sha256(f.read()).hexdigest()
            self.assertNotIn(d, digests, f"Collision between {key} and {digests.get(d)}")
            digests[d] = key
        self.assertEqual(len(digests), 40, "All 40 projectiles must have unique SHA-256 digests")

    def test_05_asset_factory_aliases(self):
        for key in self.builder_keys:
            parts = key.split("_", 1)
            pid_lower = parts[0]
            name_snake = parts[1]
            pid_upper = pid_lower.upper()

            # Canonical lookup
            surf_canonical = self.af.projectiles.get(key)
            self.assertIsNotNone(surf_canonical, f"Canonical lookup failed for {key}")
            self.assertIsInstance(surf_canonical, pygame.Surface)
            self.assertEqual(surf_canonical.get_size(), (32, 32))

            # Alias lookups
            surf_name = self.af.projectiles.get(name_snake)
            surf_pid_u = self.af.projectiles.get(pid_upper)
            surf_pid_l = self.af.projectiles.get(pid_lower)

            self.assertIs(surf_name, surf_canonical, f"Alias name_snake failed for {name_snake}")
            self.assertIs(surf_pid_u, surf_canonical, f"Alias pid_upper failed for {pid_upper}")
            self.assertIs(surf_pid_l, surf_canonical, f"Alias pid_lower failed for {pid_lower}")

            # Subscript indexing
            self.assertIs(self.af.projectiles[key], surf_canonical)
            self.assertIs(self.af.projectiles[name_snake], surf_canonical)
            self.assertIs(self.af.projectiles[pid_upper], surf_canonical)

            # In operator
            self.assertIn(key, self.af.projectiles)
            self.assertIn(name_snake, self.af.projectiles)
            self.assertIn(pid_upper, self.af.projectiles)

    def test_06_public_builder_functions(self):
        import src.assets.projectile_factory as pf
        for key in self.builder_keys:
            build_name = f"build_{key}"
            create_name = f"create_{key}"
            self.assertTrue(hasattr(pf, build_name), f"Missing public builder function: {build_name}")
            self.assertTrue(hasattr(pf, create_name), f"Missing public builder function: {create_name}")
            builder = getattr(pf, build_name)
            self.assertTrue(callable(builder))
            surf = builder()
            self.assertIsInstance(surf, pygame.Surface)
            self.assertEqual(surf.get_size(), (32, 32))

    def test_07_projectile_registry_dict_protocol(self):
        reg = self.af.projectiles.copy()
        self.assertIsInstance(reg, type(self.af.projectiles), "copy() must return a ProjectileRegistry instance")
        self.assertIsNotNone(reg.get("iron_arrow"), "Copied registry must preserve alias lookups")

        # aliases property
        self.assertIsInstance(reg.aliases, dict)
        self.assertIn("iron_arrow", reg.aliases)
        self.assertEqual(reg.aliases["iron_arrow"], "p01_iron_arrow")

        # setdefault on alias
        val = reg.setdefault("iron_arrow", None)
        self.assertIsNotNone(val)
        self.assertNotIn("iron_arrow", list(reg.keys()), "setdefault on alias must not pollute canonical keys")

        # pop on alias
        popped = reg.pop("iron_arrow")
        self.assertIs(popped, val)
        self.assertNotIn("p01_iron_arrow", reg)
        self.assertNotIn("iron_arrow", reg)

        # pop with default
        missing = reg.pop("iron_arrow", "DEFAULT")
        self.assertEqual(missing, "DEFAULT")

        # __delitem__ on alias
        self.assertIn("p02_heavy_bolt", reg)
        self.assertIn("heavy_bolt", reg)
        del reg["heavy_bolt"]
        self.assertNotIn("p02_heavy_bolt", reg)
        self.assertNotIn("heavy_bolt", reg)
        self.assertIsNone(reg.get("heavy_bolt"))

    def test_08_flexible_normalization_lookups(self):
        # .png extension lookup
        self.assertIsNotNone(self.af.projectiles.get("p01_iron_arrow.png"))
        self.assertIsNotNone(self.af.projectiles.get("iron_arrow.png"))
        self.assertIn("p01_iron_arrow.png", self.af.projectiles)

        # directory path lookup
        self.assertIsNotNone(self.af.projectiles.get("assets/projectiles/p01_iron_arrow.png"))
        self.assertIn("assets/projectiles/p01_iron_arrow.png", self.af.projectiles)

        # case and space/hyphen variants
        self.assertIsNotNone(self.af.projectiles.get("Iron Arrow"))
        self.assertIsNotNone(self.af.projectiles.get("IRON_ARROW"))
        self.assertIsNotNone(self.af.projectiles.get("P01_IRON_ARROW"))
        self.assertIn("Iron Arrow", self.af.projectiles)
        self.assertIn("P01_IRON_ARROW", self.af.projectiles)


if __name__ == "__main__":
    unittest.main()

